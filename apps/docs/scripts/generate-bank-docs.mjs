import { readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const docsRoot = path.resolve(import.meta.dirname, "../content/docs/bank");
const blocksRoot = path.resolve(import.meta.dirname, "../../packages/bank-kit-later/src/blocks");
const blocksIndex = path.join(blocksRoot, "index.tsx");
const generatedBanner = "<!-- This file is generated by `npm run build:bank-docs`. Do not edit it directly. -->";

const words = (value) => value
  .replace(/([a-z])([A-Z])/g, "$1 $2")
  .replace(/[-_]/g, " ")
  .replace(/\b\w/g, (letter) => letter.toUpperCase());

const slugFrom = (value) => value
  .replace(/([a-z])([A-Z])/g, "$1-$2")
  .replace(/\//g, "-")
  .replace(/[^a-zA-Z0-9]+/g, "-")
  .replace(/^-|-$/g, "")
  .toLowerCase();

async function getBlocks() {
  const index = await readFile(blocksIndex, "utf8");
  const exports = [...index.matchAll(/export\s*{\s*default\s+as\s+(\w+)\s*}\s*from\s*["']\.\/(.+?)["'];?/g)];

  const blocks = await Promise.all(exports.map(async ([, exportName, relativePath]) => {
    const sourcePath = path.join(blocksRoot, relativePath, "index.tsx");
    try {
      await stat(sourcePath);
    } catch {
      // Ignore stale barrel exports; only documented blocks must have a source entry point.
      return undefined;
    }

    return {
      exportName,
      sourcePath,
      slug: slugFrom(relativePath),
      title: words(exportName),
    };
  }));

  return blocks.filter(Boolean).sort((a, b) => a.slug.localeCompare(b.slug));
}

function documentFor(block, source) {
  return `${generatedBanner}
---
title: ${block.title}
description: A reusable ${block.title.toLowerCase()} block for banking interfaces.
---

import { ComponentPreview } from "@/src/components/ui/component-preview";
import { ${block.exportName} } from "@sol-ui/bank-kit/blocks";

## Preview

<ComponentPreview>
  <${block.exportName} />
</ComponentPreview>

## Installation

### CLI

\`\`\`bash
npx solui@latest add ${block.slug}
\`\`\`

### Agent

Use an MCP-compatible coding agent and ask it:

> Install the \`${block.slug}\` Sol UI component.

The agent can call the \`install_components\` tool to add the component and its dependencies to your project.

## Usage

\`\`\`tsx
import { ${block.exportName} } from "@sol-ui/bank-kit/blocks";

export function Example() {
  return <${block.exportName} />;
}
\`\`\`

## Source

\`\`\`tsx
${source.trim().replace(/\r\n/g, "\n").replace(/[ \t]+\n/g, "\n")}
\`\`\`
`;
}

async function main() {
  const blocks = await getBlocks();
  if (!blocks.length) throw new Error("No block exports with source entry points were found.");

  await Promise.all((await readdir(docsRoot)).map(async (file) => {
    if (!file.endsWith(".mdx")) return;
    const filePath = path.join(docsRoot, file);
    if ((await readFile(filePath, "utf8")).startsWith(generatedBanner)) await rm(filePath);
  }));

  await Promise.all(blocks.map(async (block) => {
    const source = await readFile(block.sourcePath, "utf8");
    await writeFile(path.join(docsRoot, `${block.slug}.mdx`), documentFor(block, source));
  }));

  console.log(`Generated ${blocks.length} bank component documents.`);
}

await main();
